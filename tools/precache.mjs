// Scan app/ and regenerate app/sw.js with a complete precache list.
// The service worker is the only generated runtime file; everything else is
// plain static assets. Run after adding, removing, or editing any app file.
//
//   node tools/precache.mjs          write app/sw.js
//   node tools/precache.mjs --check  fail if app/sw.js is stale

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(here, "..", "app");
const swPath = path.join(appDir, "sw.js");

const SKIP = new Set(["sw.js"]);
const SKIP_DIRS = new Set(["node_modules"]);

function walk(dir, base = "") {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || SKIP.has(entry.name)) continue;
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      out.push(...walk(path.join(dir, entry.name), path.posix.join(base, entry.name)));
    } else {
      out.push(path.posix.join(base, entry.name));
    }
  }
  return out;
}

const files = walk(appDir).sort();
const assets = ["./", ...files.map((file) => `./${file}`)];

const hash = crypto.createHash("sha256");
hash.update(assets.join("\n"));
for (const file of files) {
  hash.update(fs.readFileSync(path.join(appDir, file)));
}
const version = hash.digest("hex").slice(0, 12);

const template = `// Generated by tools/precache.mjs. Do not edit by hand.
// Network-first when online so updates land on the next load; cache fallback
// keeps the app fully usable offline.
const CACHE = "dregg-${version}";
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      })
      .catch(() =>
        caches.match(request).then((cached) => {
          if (cached) return cached;
          if (request.mode === "navigate") return caches.match("./index.html");
          return Response.error();
        }),
      ),
  );
});
`;

const check = process.argv.includes("--check");
const current = fs.existsSync(swPath) ? fs.readFileSync(swPath, "utf8") : "";

if (check) {
  if (current !== template) {
    console.error("app/sw.js is stale. Run: npm run precache");
    process.exit(1);
  }
  console.log(`sw.js up to date (${assets.length} assets, cache dregg-${version})`);
} else {
  fs.writeFileSync(swPath, template);
  console.log(`wrote app/sw.js (${assets.length} assets, cache dregg-${version})`);
}
