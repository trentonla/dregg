// Golden SVGs and a visual review sheet.
//
//   node tools/golden.mjs            write docs/outline-sheet.html
//   node tools/golden.mjs --update   also write tests/golden/*.svg
//   node tools/golden.mjs --check    fail if any committed snapshot is stale

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { outlineForUnit, outlineForWord, outlineSvg, renderOutline } from "../app/js/outline.js";
import { LEXICON_BY_WORD } from "../app/js/data/lexicon.js";
import { CONSONANTS, VOWELS, DIPHTHONGS, GLIDES, BLENDS, UNIT_BY_ID } from "../app/js/units.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const snapshotDir = path.join(root, "tests", "golden");
const sheetPath = path.join(root, "docs", "outline-sheet.html");

export const GOLDEN_UNITS = ["t", "d", "n", "m", "a1", "e1", "o1", "u1", "ai", "ng", "w", "blend-ten"];
export const GOLDEN_WORDS = ["team", "running", "people", "machine", "think", "boy", "use", "we", "yes", "hot", "art", "near", "tears", "job", "box"];

export function goldenSamples() {
  const samples = [];
  for (const id of GOLDEN_UNITS) {
    samples.push({ name: `unit-${id}`, svg: outlineSvg(outlineForUnit(id, "precision"), { label: UNIT_BY_ID[id]?.label || id }) });
  }
  for (const word of GOLDEN_WORDS) {
    const record = LEXICON_BY_WORD[word];
    if (!record) throw new Error(`Golden word missing from lexicon: ${word}`);
    samples.push({ name: `word-${word}`, svg: outlineSvg(outlineForWord(record, "precision"), { label: word }) });
  }
  return samples;
}

function grid(ids, track = "precision") {
  return `<div class="grid">${ids
    .map(
      (id) =>
        `<figure><div class="art">${outlineSvg(outlineForUnit(id, track), { label: UNIT_BY_ID[id]?.label || id })}</div><figcaption>${UNIT_BY_ID[id]?.label || id}<small>${id}</small></figcaption></figure>`,
    )
    .join("")}</div>`;
}

function sheet() {
  const words = GOLDEN_WORDS.map((word) => {
    const record = LEXICON_BY_WORD[word];
    return `<tr><td>${word}</td><td class="units">${record.full.join(" ")}</td><td class="art">${outlineSvg(outlineForWord(record, "precision"), { label: word })}</td></tr>`;
  }).join("");
  const joins = [
    ["pr", ["p", "r"]],
    ["pl", ["p", "l"]],
    ["br", ["b", "r"]],
    ["fr", ["f", "r"]],
    ["kr", ["k", "r"]],
    ["gl", ["g", "l"]],
    ["rk", ["r", "k"]],
    ["ld", ["l", "d"]],
  ];
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Dregg outline sheet</title>
<style>
  body { margin: 2rem; background: #fbfaf7; color: #1c1b18; font: 14px/1.5 system-ui, sans-serif; }
  h1, h2 { font-family: "Iowan Old Style", Palatino, Georgia, serif; font-weight: 500; }
  h1 { font-size: 2rem; } h2 { margin-top: 2.5rem; border-top: 1px solid #e7e4dc; padding-top: 1rem; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(90px, 1fr)); gap: 12px; }
  figure { margin: 0; border: 1px solid #e7e4dc; border-radius: 8px; padding: 8px; background: #fff; text-align: center; }
  .art svg { width: 100%; height: 64px; }
  figcaption { font-family: "Iowan Old Style", Palatino, Georgia, serif; }
  figcaption small { display: block; font: 11px ui-monospace, monospace; color: #6b6861; }
  table { border-collapse: collapse; width: 100%; }
  td, th { border-bottom: 1px solid #e7e4dc; padding: 8px; text-align: left; vertical-align: middle; }
  td.art svg { width: 180px; height: 70px; }
  td.units { font: 12px ui-monospace, monospace; color: #6b6861; }
  .note { color: #6b6861; max-width: 70ch; }
</style></head>
<body>
  <h1>Dregg outline sheet</h1>
  <p class="note">Generated by <code>tools/golden.mjs</code>. Open at phone and desktop width and compare against the 1916 chart. Approximations are logged in <code>OUTLINE-NOTES.md</code>; this sheet is for review, not authority.</p>
  <h2>Consonants</h2>${grid(CONSONANTS.map((unit) => unit.id))}
  <h2>Vowels</h2>${grid(VOWELS.map((unit) => unit.id))}
  <h2>Diphthongs and glides</h2>${grid([...DIPHTHONGS, ...GLIDES].map((unit) => unit.id))}
  <h2>Blends</h2>${grid(BLENDS.map((unit) => unit.id))}
  <h2>Joins</h2>
  <div class="grid">${joins
    .map(
      ([label, units]) =>
        `<figure><div class="art">${outlineSvg(renderOutline(units, "precision", { word: label }), { label })}</div><figcaption>${label}</figcaption></figure>`,
    )
    .join("")}</div>
  <h2>Words</h2>
  <table><thead><tr><th>Word</th><th>Units</th><th>Outline</th></tr></thead><tbody>${words}</tbody></table>
</body></html>`;
}

async function main() {
  const check = process.argv.includes("--check");
  const update = process.argv.includes("--update");

  if (!check) {
    fs.mkdirSync(path.dirname(sheetPath), { recursive: true });
    fs.writeFileSync(sheetPath, sheet());
    console.log(`wrote ${path.relative(root, sheetPath)}`);
  }

  const samples = goldenSamples();
  if (check) {
    const stale = samples.filter((sample) => {
      const file = path.join(snapshotDir, `${sample.name}.svg`);
      return !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== `${sample.svg}\n`;
    });
    if (stale.length) {
      console.error(`stale golden snapshots: ${stale.map((sample) => sample.name).join(", ")}`);
      console.error("Run: node tools/golden.mjs --update");
      process.exit(1);
    }
    console.log(`golden snapshots up to date (${samples.length})`);
    return;
  }

  if (update) {
    fs.mkdirSync(snapshotDir, { recursive: true });
    for (const sample of samples) {
      fs.writeFileSync(path.join(snapshotDir, `${sample.name}.svg`), `${sample.svg}\n`);
    }
    console.log(`wrote ${samples.length} snapshots to ${path.relative(root, snapshotDir)}`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
